package com.helger.pgcc.parser;

import org.jspecify.annotations.NonNull;

import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

import com.helger.pgcc.parser.exp.ExpRStringLiteral;

// A simple class to hold the data generated by the tokenizer. This is passed to
// the code generators to produce code.
  /**
   * The tokenizer of one grammar, in a form that can be run directly rather than written out as
   * source. JavaCCInterpreter uses it to tokenize input without generating and compiling a token
   * manager first, and the lexer generator fills it in alongside the code it emits.
   */
public class TokenizerData
{
  /** Default constructor. */
  public TokenizerData ()
  {}

  // Name of the parser as specified in the PARSER_BEGIN/PARSER_END block.
  private String m_sParserName;
  // Decls coming from TOKEN_MGR_DECLS
  private String m_sDecls;
  // A map of <LexState, first char> to a sequence of literals indexed by:
  // ((int0LexicalState << 16 | (int)c)
  // The literals in the list are all guaranteed to start with the char and re
  // sorted by length so that the "longest-match" rule is done trivially by
  // just going through the sequence in the order.
  // Since they are all literals, there is no duplication (JavaCC checks that)
  // and hence if a longer match is matched, no need to check the shorter match.
  private Map <Integer, List <String>> m_aLiteralSequence;
  // A map of list of kind values indexed by ((int0LexicalState << 16 | (int)c)
  // same key as before.
  private Map <Integer, List <Integer>> m_aLiteralKinds;
  // The NFA start state for a given string literal match. We use this to start
  // the NFA if needed after a literal match is completed.
  private Map <Integer, Integer> m_aKindToNfaStartState;
  /** The main NFA, by state index. */
  private final Map <Integer, NfaState> m_aNfa = new HashMap <> ();
  // On match info indexed by the match kind.
  private final Map <Integer, MatchInfo> m_aAllMatches = new HashMap <> ();
  // Initial nfa states indexed by lexical state.
  private Map <Integer, Integer> m_aInitialStates;
  // Kind of the wildcard match (~[]) indexed by lexical state.
  private Map <Integer, Integer> m_aWildcardKind;
  // Name of lexical state - for debugging.
  private String [] m_aLexStateNames;
  // DEFAULT lexical state index.
  private int m_nDefaultLexState;

  /**
   * The parser name, as the PARSER_BEGIN of the grammar gives it.
   *
   * @return The parser name. May be <code>null</code> before generation starts.
   */
  public String getParserName ()
  {
    return m_sParserName;
  }

  /**
   * The parser name, as the PARSER_BEGIN of the grammar gives it.
   *
   * @param sParserName
   *        The parser name.
   */
  public void setParserName (final String sParserName)
  {
    this.m_sParserName = sParserName;
  }

  /**
   * The declarations from the TOKEN_MGR_DECLS section.
   *
   * @return The declarations. May be <code>null</code> if the grammar has no such section.
   */
  public String getDecls ()
  {
    return m_sDecls;
  }

  /**
   * The declarations from the TOKEN_MGR_DECLS section.
   *
   * @param sDecls
   *        The declarations.
   */
  public void setDecls (final String sDecls)
  {
    this.m_sDecls = sDecls;
  }

  /**
   * The string literals that can start with a given character, keyed by
   * <code>lexicalState &lt;&lt; 16 | c</code> and sorted by length. Going through a list in order
   * gives the longest match for free, and no two entries can be equal because the grammar checker
   * rejects duplicate literals.
   *
   * @return The literals per lexical state and first character. May be <code>null</code> before generation
   *   *         starts.
   */
  public Map <Integer, List <String>> getLiteralSequence ()
  {
    return m_aLiteralSequence;
  }

  /**
   * The string literals that can start with a given character, keyed by
   * <code>lexicalState &lt;&lt; 16 | c</code> and sorted by length. Going through a list in order
   * gives the longest match for free, and no two entries can be equal because the grammar checker
   * rejects duplicate literals.
   *
   * @param aLiteralSequence
   *        The literals per lexical state and first character.
   */
  public void setLiteralSequence (final Map <Integer, List <String>> aLiteralSequence)
  {
    this.m_aLiteralSequence = aLiteralSequence;
  }

  /**
   * The token kind of each entry of {@link #getLiteralSequence()}, under the same key and in the
   * same order.
   *
   * @return The kinds per lexical state and first character. May be <code>null</code> before generation
   *   *         starts.
   */
  public Map <Integer, List <Integer>> getLiteralKinds ()
  {
    return m_aLiteralKinds;
  }

  /**
   * The token kind of each entry of {@link #getLiteralSequence()}, under the same key and in the
   * same order.
   *
   * @param aLiteralKinds
   *        The kinds per lexical state and first character.
   */
  public void setLiteralKinds (final Map <Integer, List <Integer>> aLiteralKinds)
  {
    this.m_aLiteralKinds = aLiteralKinds;
  }

  /**
   * The NFA state to continue in once a string literal has matched, keyed by the kind of that
   * literal. A longer token may still be coming.
   *
   * @return The start states per kind. May be <code>null</code> before generation starts.
   */
  public Map <Integer, Integer> getKindToNfaStartState ()
  {
    return m_aKindToNfaStartState;
  }

  /**
   * The NFA state to continue in once a string literal has matched, keyed by the kind of that
   * literal. A longer token may still be coming.
   *
   * @param aKindToNfaStartState
   *        The start states per kind.
   */
  public void setKindToNfaStartState (final Map <Integer, Integer> aKindToNfaStartState)
  {
    this.m_aKindToNfaStartState = aKindToNfaStartState;
  }

  /**
   * The automaton itself, keyed by state index.
   *
   * @return The states. Never <code>null</code>.
   */
  public Map <Integer, NfaState> getNfa ()
  {
    return m_aNfa;
  }

  /**
   * Add one state to the automaton.
   *
   * @param nIndex
   *        The state index, which is also its key.
   * @param characters
   *        The characters this state can move on. May not be <code>null</code>.
   * @param nextStates
   *        The states reachable from here. May not be <code>null</code>.
   * @param aCompositeStates
   *        The states this one stands for, if it is a composite one. May be <code>null</code>.
   * @param nKind
   *        The token kind matched here, or {@link Integer#MAX_VALUE} if this is not a final
   *         state.
   */
  public void addNfaState (final int nIndex,
                           final Set <Character> characters,
                           final Set <Integer> nextStates,
                           final Set <Integer> aCompositeStates,
                           final int nKind)
  {
    final NfaState aNfaState = new NfaState (nIndex, characters, nextStates, aCompositeStates, nKind);
    m_aNfa.put (Integer.valueOf (nIndex), aNfaState);
  }

  /**
   * What happens when each token kind matches - whether it produces a token, skips or continues,
   * which lexical state it switches to, and the action it carries.
   *
   * @return The match information per kind. Never <code>null</code>.
   */
  public Map <Integer, MatchInfo> getAllMatches ()
  {
    return m_aAllMatches;
  }

  /**
   * Record what each token kind does once the whole grammar has been read: whether it produces a
   * token, skips, continues with MORE or produces a special token, which lexical state it
   * switches to, and the action it carries.
   *
   * @param aActions
   *        The lexical action of each kind, keyed by kind. May not be <code>null</code>.
   * @param aNewLexStateIndices
   *        The lexical state each kind switches to, indexed by kind, or -1 to stay. May not be
   *         <code>null</code>.
   * @param aToSkip
   *        The kinds that skip, as a bit set over the ordinals. May not be <code>null</code>.
   * @param aToSpecial
   *        The kinds that are special tokens, as a bit set over the ordinals. May not be
   *         <code>null</code>.
   * @param aToMore
   *        The kinds that continue with MORE, as a bit set over the ordinals. May not be
   *         <code>null</code>.
   * @param aToToken
   *        The kinds that produce a token, as a bit set over the ordinals. May not be
   *         <code>null</code>.
   */
  public void updateMatchInfo (@NonNull final Map <Integer, String> aActions,
                               @NonNull final int [] aNewLexStateIndices,
                               @NonNull final long [] aToSkip,
                               @NonNull final long [] aToSpecial,
                               @NonNull final long [] aToMore,
                               @NonNull final long [] aToToken)
  {
    for (int i = 0; i < aNewLexStateIndices.length; i++)
    {
      final int nVectorIndex = i >> 6;
      final long nBits = (1L << (i & 077));
      EMatchType eMatchType = EMatchType.TOKEN;
      if (aToSkip.length > nVectorIndex && (aToSkip[nVectorIndex] & nBits) != 0L)
      {
        eMatchType = EMatchType.SKIP;
      }
      else
        if (aToSpecial.length > nVectorIndex && (aToSpecial[nVectorIndex] & nBits) != 0L)
        {
          eMatchType = EMatchType.SPECIAL_TOKEN;
        }
        else
          if (aToMore.length > nVectorIndex && (aToMore[nVectorIndex] & nBits) != 0L)
          {
            eMatchType = EMatchType.MORE;
          }
          else
          {
            assert (aToToken.length > nVectorIndex && (aToToken[nVectorIndex] & nBits) != 0L);
            eMatchType = EMatchType.TOKEN;
          }
      final MatchInfo aMatchInfo = new MatchInfo (Options.isIgnoreCase () ? null
                                                                          : ExpRStringLiteral.strLit ()
                                                                                             .getAllImages ()[i],
                                                  i,
                                                  eMatchType,
                                                  aNewLexStateIndices[i],
                                                  aActions.get (Integer.valueOf (i)));
      m_aAllMatches.put (Integer.valueOf (i), aMatchInfo);
    }
  }

  /**
   * The NFA state a match starts in, keyed by lexical state.
   *
   * @return The start states per lexical state. May be <code>null</code> before generation starts.
   */
  public Map <Integer, Integer> getInitialStates ()
  {
    return m_aInitialStates;
  }

  /**
   * The NFA state a match starts in, keyed by lexical state.
   *
   * @param aInitialStates
   *        The start states per lexical state.
   */
  public void setInitialStates (final Map <Integer, Integer> aInitialStates)
  {
    this.m_aInitialStates = aInitialStates;
  }

  /**
   * The kind of the <code>~[]</code> match, keyed by lexical state.
   *
   * @return The kinds per lexical state. May be <code>null</code> before generation starts.
   */
  public Map <Integer, Integer> getWildcardKind ()
  {
    return m_aWildcardKind;
  }

  /**
   * The kind of the <code>~[]</code> match, keyed by lexical state.
   *
   * @param aWildcardKind
   *        The kinds per lexical state.
   */
  public void setWildcardKind (final Map <Integer, Integer> aWildcardKind)
  {
    this.m_aWildcardKind = aWildcardKind;
  }

  /**
   * The declared name of each lexical state, indexed by lexical state. Only the debug output uses
   * them.
   *
   * @return The names, indexed by lexical state. May be <code>null</code> before generation starts.
   */
  public String [] getLexStateNames ()
  {
    return m_aLexStateNames;
  }

  /**
   * The declared name of each lexical state, indexed by lexical state. Only the debug output uses
   * them.
   *
   * @param aLexStateNames
   *        The names, indexed by lexical state.
   */
  public void setLexStateNames (final String [] aLexStateNames)
  {
    this.m_aLexStateNames = aLexStateNames;
  }

  /**
   * The lexical state a match starts in.
   *
   * @return The index into {@link #getLexStateNames()}.
   */
  public int getDefaultLexState ()
  {
    return m_nDefaultLexState;
  }

  /**
   * The lexical state a match starts in.
   *
   * @param nDefaultLexState
   *        The index into {@link #getLexStateNames()}.
   */
  public void setDefaultLexState (final int nDefaultLexState)
  {
    this.m_nDefaultLexState = nDefaultLexState;
  }

  // Class representing NFA state.
  /**
   * One state of the NFA the interpreter walks.
   *
   * @param index
   *        Index of the state.
   * @param characters
   *        The characters this state can move on. May not be <code>null</code>.
   * @param nextStates
   *        The states reachable from here. May not be <code>null</code>.
   * @param compositeStates
   *        The states this one stands for, if it is a composite one. The initial state has to
   *        transition to several states at once so that the NFA tries every possibility. May not be
   *        <code>null</code>.
   * @param kind
   *        The token kind matched here, or {@link Integer#MAX_VALUE} if this is not a final state.
   */
  public record NfaState (int index,
                          Set <Character> characters,
                          Set <Integer> nextStates,
                          Set <Integer> compositeStates,
                          int kind)
  {}

  /** What a matched kind does with the input. */
  public static enum EMatchType
  {
    /** Throw the match away and start again. */
    SKIP,
    /** Produce a token that the parser does not see, but that stays attached to the next one. */
    SPECIAL_TOKEN,
    /** Keep the match and go on collecting, so that a longer token can be built from it. */
    MORE,
    /** Produce a token and hand it to the parser. */
    TOKEN,
  }

  /**
   * What matching a kind means: which token it is and what it does to the lexical state.
   *
   * @param image
   *        The string literal image if this is a string literal token, <code>null</code> otherwise.
   * @param kind
   *        The token kind.
   * @param matchType
   *        Whether this produces a token, a skip, a special token or more input.
   * @param newLexState
   *        The lexical state to switch to, or -1 to stay.
   * @param action
   *        The action to run, or <code>null</code> if there is none.
   */
  public record MatchInfo (String image, int kind, EMatchType matchType, int newLexState, String action)
  {}
}
